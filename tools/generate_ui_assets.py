#!/usr/bin/env python3
"""Convert the documented interface artwork to uncompressed LVGL image data."""
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "main/assets"


def rgba(name, width, height):
    data = subprocess.check_output([
        "ffmpeg", "-v", "error", "-i", str(ASSETS / name),
        "-frames:v", "1",
        "-f", "rawvideo", "-pix_fmt", "rgba", "pipe:1",
    ])
    assert len(data) == width * height * 4
    return data


def emit(name, width, height, color_format, stride, data):
    lines = [f"static const uint8_t {name}_data[] = {{"]
    lines += ["    " + ", ".join(f"0x{v:02x}" for v in data[i:i + 16]) + ","
              for i in range(0, len(data), 16)]
    lines += ["};", f"const lv_image_dsc_t {name} = {{",
              "    .header = {.magic = LV_IMAGE_HEADER_MAGIC,",
              f"               .cf = LV_COLOR_FORMAT_{color_format}, .w = {width}, .h = {height}, .stride = {stride}}},",
              f"    .data_size = sizeof({name}_data), .data = {name}_data,", "};", ""]
    return "\n".join(lines)


source = '// SPDX-License-Identifier: Apache-2.0\n'
source += '// Generated by tools/generate_ui_assets.py; source attribution is in assets/README.md.\n'
source += '#include "ui_assets.h"\n\n'
for name, filename, width, height in (
    ("webcam_camera_icon", "camera.png", 118, 118),
    ("webcam_camera_guide_device", "camera-guide-device.png", 240, 176),
):
    pixels = rgba(filename, width, height)
    rgb565 = bytearray()
    for i in range(0, len(pixels), 4):
        r, g, b, a = pixels[i:i + 4]
        r, g, b = (v * a // 255 for v in (r, g, b))
        rgb565 += (((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)).to_bytes(2, "little")
    assert len(rgb565) == width * height * 2
    source += emit(name, width, height, "RGB565", width * 2, rgb565)

arrow = rgba("camera-guide-arrow.png", 82, 36)
bgra = bytearray()
for i in range(0, len(arrow), 4):
    r, g, b, a = arrow[i:i + 4]
    bgra += bytes((b, g, r, a))
source += emit("webcam_camera_guide_arrow", 82, 36, "ARGB8888", 82 * 4, bgra)
(ROOT / "main/ui_assets.c").write_text(source)
