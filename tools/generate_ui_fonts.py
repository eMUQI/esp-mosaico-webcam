#!/usr/bin/env python3
"""Generate the Chinese glyph subsets used by the webcam interface."""
import argparse
import hashlib
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]
FONT_SHA256 = "2c76254f6fc379fddfce0a7e84fb5385bb135d3e399294f6eeb6680d0365b74b"

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--font", required=True, type=Path, help="Official NotoSansCJKsc-Regular.otf")
args = parser.parse_args()
if hashlib.sha256(args.font.read_bytes()).hexdigest() != FONT_SHA256:
    raise SystemExit("Font source differs from the documented Noto Sans CJK source")
symbols = "".join(sorted({char for char in (ROOT / "main/preview_ui.c").read_text() if ord(char) > 127}))
for size in (14, 20):
    output = ROOT / f"main/ui_font_{size}.c"
    subprocess.run([
        "lv_font_conv", "--font", str(args.font), "--symbols", symbols,
        "--lv-include", "lvgl.h", "--size", str(size), "--bpp", "4", "--no-compress", "--format", "lvgl",
        "--lv-font-name", f"webcam_font_{size}",
        "--lv-fallback", f"lv_font_montserrat_{size}", "-o", str(output),
    ], check=True)
    text = output.read_text().replace(str(args.font), args.font.name).replace(str(output), output.name)
    output.write_text("// Generated by tools/generate_ui_fonts.py; license and source: assets/README.md.\n" + text)
